/* 没有的字画成实心方块，一眼看出缺字，而不是悄悄空着 */
static const uint8_t k_missing[7] = {0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F};

static const uint8_t *find_glyph(char c)
{
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    for (size_t i = 0; i < sizeof k_glyphs / sizeof k_glyphs[0]; ++i) {
        if (k_glyphs[i].ch == c) {
            return k_glyphs[i].rows;
        }
    }
    return k_missing;
}

static void draw_char(uint16_t x, uint16_t y, char c, uint8_t s, uint16_t fg, uint16_t bg)
{
    const uint8_t *rows = find_glyph(c);
    bsp_lcd_fill(x, y, (uint16_t)(x + 6u * s - 1u), (uint16_t)(y + 8u * s - 1u), bg);
    /* 每行把连续的亮点合成一段一起填，比逐点填少开很多次窗 */
    for (uint8_t r = 0; r < 7u; ++r) {
        uint8_t col = 0;
        while (col < 5u) {
            if ((rows[r] & (0x10u >> col)) == 0u) {
                ++col;
                continue;
            }
            const uint8_t start = col;
            while (col < 5u && (rows[r] & (0x10u >> col)) != 0u) {
                ++col;
            }
            const uint32_t sc = s;
            const uint16_t px0 = (uint16_t)(x + start * sc);
            const uint16_t px1 = (uint16_t)(x + col * sc - 1u);
            const uint16_t py0 = (uint16_t)(y + r * sc);
            const uint16_t py1 = (uint16_t)(py0 + sc - 1u);
            bsp_lcd_fill(px0, py0, px1, py1, fg);
        }
    }
}

uint16_t gfx_text_width(const char *s, uint8_t scale)
{
    uint16_t n = 0;
    while (s[n] != '\0') {
        ++n;
    }
    return (uint16_t)(n * 6u * scale);
}

uint16_t gfx_text(uint16_t x, uint16_t y, const char *s, uint8_t scale, uint16_t fg, uint16_t bg)
{
    for (; *s != '\0'; ++s) {
        if (x + 6u * scale > BSP_LCD_W) {
            break;
        }
        draw_char(x, y, *s, scale, fg, bg);
        x = (uint16_t)(x + 6u * scale);
    }
    return x;
}

/* 段位：bit0..6 = a b c d e f g（上、右上、右下、下、左下、左上、中） */
static const uint8_t k_seg[10] = {0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07, 0x7F, 0x6F};

void gfx_seg_digit(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t t, uint8_t digit, uint16_t fg,
                   uint16_t bg)
{
    bsp_lcd_fill(x, y, (uint16_t)(x + w - 1u), (uint16_t)(y + h - 1u), bg);
    if (digit > 9u) {
        return;
    }
    const uint8_t m = k_seg[digit];
    const uint16_t x1 = (uint16_t)(x + w - 1u);
    const uint16_t y1 = (uint16_t)(y + h - 1u);
    const uint16_t ym = (uint16_t)(y + (h - t) / 2u); /* 中段上沿 */
    if (m & 0x01u) {
        bsp_lcd_fill(x, y, x1, (uint16_t)(y + t - 1u), fg);
    }
    if (m & 0x02u) {
        bsp_lcd_fill((uint16_t)(x1 - t + 1u), y, x1, (uint16_t)(ym + t - 1u), fg);
    }
    if (m & 0x04u) {
        bsp_lcd_fill((uint16_t)(x1 - t + 1u), ym, x1, y1, fg);
    }
    if (m & 0x08u) {
        bsp_lcd_fill(x, (uint16_t)(y1 - t + 1u), x1, y1, fg);
    }
    if (m & 0x10u) {
        bsp_lcd_fill(x, ym, (uint16_t)(x + t - 1u), y1, fg);
    }
    if (m & 0x20u) {
        bsp_lcd_fill(x, y, (uint16_t)(x + t - 1u), (uint16_t)(ym + t - 1u), fg);
    }
    if (m & 0x40u) {
        bsp_lcd_fill(x, ym, x1, (uint16_t)(ym + t - 1u), fg);
    }
}
